#!/usr/bin/env node
/**
 * Stamp the skin's client sources with a deterministic build id.
 *
 * Why this exists: the skin ships as a *versioned, immutable* browser bundle. A
 * window that is running an older revision cannot discover that fact — the host's
 * HMR client only reacts to `rebuilt` frames and ignores the `graph` frame that
 * carries current revisions — and because old revisions stop resolving after a
 * DSH restart, such a window simply keeps rendering the old build forever. The
 * settings panel is the one place a user already looks, so the build id is baked
 * into the panel heading: open 设置 → 皮肤管理 → 深海女仆工坊 and you can see at a
 * glance which build that window actually loaded.
 *
 * The id must be *deterministic* rather than time-based: this repository commits
 * its built `lib/`, the manager identifies builds by fingerprint, and a
 * timestamp would make every rebuild differ from the committed artifact. So the
 * id is a SHA-256 over `src/**` (LF-normalised, path and length framed, in sorted
 * order), truncated to 12 hex — it changes exactly when the bundled sources do.
 *
 * `tests/build-id.spec.ts` recomputes the same hash and compares it with the
 * committed constant, so editing `src/**` without rebuilding fails the suite
 * instead of shipping a heading that lies about which sources are inside.
 *
 * Run: node scripts/write-skin-build-id.mjs <skin-root>
 */
import { createHash } from 'node:crypto'
import { readdirSync, readFileSync, renameSync, statSync, writeFileSync } from 'node:fs'
import { join, relative, resolve, sep } from 'node:path'
import { pathToFileURL } from 'node:url'

/** Where the stamped constant lands, relative to the skin root. */
export const BUILD_ID_MODULE = 'src/client/build-id.generated.ts'

/** The generated module is an output, so it must never feed its own hash. */
const EXCLUDE = new Set([BUILD_ID_MODULE.split('/').join(sep)])

/** Every file under `dir`, as skin-root-relative POSIX paths, in sorted order. */
function walk(root, dir) {
  const found = []
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name)
    if (entry.isDirectory()) found.push(...walk(root, full))
    else if (entry.isFile()) found.push(relative(root, full).split(sep).join('/'))
  }
  return found
}

/**
 * Hash the inputs that determine the client bundle.
 *
 * @param skinRoot - Absolute path of the skin package.
 * @returns 12 lowercase hex characters.
 */
export function computeSkinSourceId(skinRoot) {
  const root = resolve(skinRoot)
  const files = walk(root, join(root, 'src'))
    .filter((file) => !EXCLUDE.has(file.split('/').join(sep)))
    .sort()
  const hash = createHash('sha256')
  for (const file of files) {
    // LF-normalise so a CRLF checkout (core.autocrlf) hashes the same as LF.
    const text = readFileSync(join(root, file), 'utf8').replaceAll('\r\n', '\n')
    const bytes = Buffer.byteLength(text)
    hash.update(`${file}\0${bytes}\0`)
    hash.update(text)
  }
  return hash.digest('hex').slice(0, 12)
}

/** The module body, written atomically so a failed build cannot leave it truncated. */
function moduleSource(id) {
  return `/**
 * Generated by scripts/write-skin-build-id.mjs — do not edit.
 *
 * A deterministic id for the sources inside this bundle. It is shown in the
 * skin's settings panel so an out-of-date window is visible instead of silent.
 */
export const MAID_ATELIER_BUILD_ID = '${id}'
`
}

function main() {
  const [skinRootArg] = process.argv.slice(2)
  if (!skinRootArg) {
    console.error('usage: node scripts/write-skin-build-id.mjs <skin-root>')
    process.exitCode = 2
    return
  }
  const root = resolve(skinRootArg)
  if (!statSync(join(root, 'src')).isDirectory()) {
    console.error(`write-skin-build-id: no src/ under ${root}`)
    process.exitCode = 2
    return
  }
  const id = computeSkinSourceId(root)
  const target = join(root, BUILD_ID_MODULE)
  const temporary = `${target}.tmp`
  writeFileSync(temporary, moduleSource(id))
  renameSync(temporary, target)
  console.log(`skin-build-id: ${id} -> ${BUILD_ID_MODULE}`)
}

// Only write when executed, so the test suite can import the hash function.
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) main()
